#include <stdio.h>   

int main(void)
{
    int n;                       
    if (scanf("%d", &n) != 1) {
        return 0;
    }

    /*
     * 数学推导（注释说明，代码只用结论）：
     *
     * 设这 n 个连续奇数的第一个是 a，公差是 2，
     * 则它们依次是：a, a+2, a+4, ..., a+2*(n-1)
     *
     * 等差求和：
     *   和 = n * (a + 末项) / 2
     *      = n * (a + a + 2*(n-1)) / 2
     *      = n * (a + n - 1)
     *
     * 题目要求这个和等于 n^3，所以：
     *   n * (a + n - 1) = n^3
     *   a + n - 1       = n^2        （两边除以 n，n>0）
     *   a               = n^2 - n + 1
     * -------------------------------------------------------- */
    int first = n * n - n + 1;   /* 第一个奇数 */

    /* 循环 n 次，依次打印这 n 个奇数 */
    for (int i = 0; i < n; i++) {
        /* 第 i 个数 = 第一个数 + 2*i */
        printf("%d", first + 2 * i);

        /* 数字之间用空格隔开；最后一个数后面不加空格 */
        if (i < n - 1) {
            printf(" ");
        }
    }

    /* 输出结束，换行 */
    printf("\n");

    return 0;
}